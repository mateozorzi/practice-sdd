enum class GameLoopAction : uint8_t {

    DISCONNECT = 0xDD,
    SEND_UPDATE_POSITIONS = 0x10,
    SEND_RACE = 0x11,
    START_RACE = 0x12,
    SEND_LEADERBOARD = 0x13,
    START_SHOP = 0x14,
    START_COUNTDOWN = 0x15,
    GAME_FINISHED = 0x16,
    RETURN_TO_LOBBY = 0x17,
    LEADERBOARD = 0x18,
    WINNER_PHASE = 0x19,
    COUNTDOWN_TIME = 0x20,
    SEND_UPGRADES_REMAINING = 0x21,
    SEND_UPGRADE_SHOP_TIME_REMAINING = 0x22,
    RACE_TIME = 0x23,
};


