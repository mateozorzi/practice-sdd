enum class ClientAction : uint8_t {

    DISCONNECT = 0x0D,
    SEND_CAR_SELECTION = 0x01,
    SEND_UPGRADE = 0x02,
    SEND_CAR_MOVEMENT = 0x03,
    CHEAT_WIN_RACE = 0x05,
    CHEAT_WIN_GAME = 0x06,
    CHEAT_INFINITE_HEALTH = 0x07,

};

